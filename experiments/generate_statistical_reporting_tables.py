"""Generate paper-facing statistical reporting and breakdown tables.

This is a post-processing script: it reads completed experiment artifacts and
writes LaTeX tables that make the statistical reporting policy consistent
across Exp 1--6. It does not invent missing reruns or relabel manual audits.
"""
from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
TABLE_DIR = REPO_ROOT / "paper" / "tables"


def _load(path: str) -> Any:
    return json.loads((REPO_ROOT / path).read_text())


def _fmt(x: Any, digits: int = 3) -> str:
    try:
        f = float(x)
    except (TypeError, ValueError):
        return "--"
    if math.isnan(f):
        return "--"
    return f"{f:.{digits}f}"


def _fmt_pm(mean: Any, std: Any | None) -> str:
    if std is None:
        return _fmt(mean)
    return f"{_fmt(mean)} $\\pm$ {_fmt(std)}"


def _fmt_ci(ci: Any) -> str:
    if not isinstance(ci, list | tuple) or len(ci) != 2:
        return "--"
    return f"[{_fmt(ci[0])},{_fmt(ci[1])}]"


def _manual_label_rate(stats: dict[str, Any], label: str, fallback: Any) -> Any:
    n = stats.get("n")
    counts = stats.get("label_counts") or {}
    if n:
        return counts.get(label, 0) / n
    return fallback


def _exp5_label_source_note() -> str:
    labels_path = REPO_ROOT / "experiments/exp05_cve_attribution/manual_audit_labels.jsonl"
    if not labels_path.exists():
        return ""
    total = 0
    assistant = 0
    for line in labels_path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        total += 1
        row = json.loads(line)
        if "assistant-assisted" in str(row.get("notes") or "").lower():
            assistant += 1
    if assistant:
        human = total - assistant
        return f" Source mix: {human} human-filled labels and {assistant} assistant-assisted evidence-only labels."
    return ""


def _escape(text: str) -> str:
    return (
        str(text)
        .replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("%", "\\%")
        .replace("&", "\\&")
    )


def _write(path: Path, lines: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def write_exp6a_main_table() -> None:
    data = _load("experiments/exp03_dynamic_service/results/exp6a_rerun/result.json")
    comparison = data["comparison"]
    full = comparison["full_rescan"]
    selective = comparison["selective_rescan"]
    rows = [
        (
            "Full rescan",
            _fmt(full.get("precision_mean")),
            _fmt(full.get("recall_mean")),
            _fmt(full.get("latency_mean_weeks")),
            _fmt(full.get("stale_asset_rate_mean")),
            _fmt(full.get("lifecycle_classification_accuracy_mean")),
            _fmt(full.get("probe_saving_rate")),
        ),
        (
            "Selective re-scan",
            _fmt_pm(selective.get("precision_mean"), selective.get("precision_std")),
            _fmt_pm(selective.get("recall_mean"), selective.get("recall_std")),
            _fmt_pm(selective.get("latency_mean_weeks"), selective.get("latency_std_weeks")),
            _fmt_pm(selective.get("stale_asset_rate_mean"), selective.get("stale_asset_rate_std")),
            _fmt_pm(
                selective.get("lifecycle_classification_accuracy_mean"),
                selective.get("lifecycle_classification_accuracy_std"),
            ),
            _fmt_pm(selective.get("probe_saving_rate_mean"), selective.get("probe_saving_rate_std")),
        ),
    ]
    lines = [
        "% Auto-generated by experiments/generate_statistical_reporting_tables.py",
        "\\begin{table*}[t]",
        "  \\centering",
        "  \\caption{Exp 6-A: dynamic attack-surface change detection. One synthetic cycle corresponds to one deployment week. Recall includes sub-interval flaps in the denominator, which no periodic scanner can observe.}",
        "  \\label{tab:exp03_main}",
        "  \\small",
        "  \\setlength{\\tabcolsep}{5pt}",
        "  \\begin{tabular}{lrrrrrr}",
        "    \\toprule",
        "    Strategy & Precision & Recall & Latency (wk) & Stale Asset Rate & Lifecycle Acc. & Probe Saving \\\\",
        "    \\midrule",
    ]
    for row in rows:
        lines.append("    " + " & ".join(row) + " \\\\")
    lines.extend([
        "    \\bottomrule",
        "  \\end{tabular}",
        "  \\vspace{0.35em}",
        "  \\begin{minipage}{0.98\\linewidth}",
        "    \\footnotesize",
        "    \\textit{Notes.} The injected taxonomy covers new subdomains, asset retirement, port open/close, service-version drift, technology-stack drift, CVE attribution drift, and stale evidence. Lifecycle states are new, active, changed, stale, and retired.",
        "  \\end{minipage}",
        "\\end{table*}",
    ])
    _write(TABLE_DIR / "exp03_main.tex", lines)


def write_exp5_main_table() -> None:
    summary = _load("experiments/exp05_cve_attribution/results/dry_run_strict/summary.json")
    manual = _load("experiments/exp05_cve_attribution/results/dry_run_strict/manual_stats.json")
    queue = manual.get("audit_queue") or {}
    queue_status = str(queue.get("status") or "")
    queue_completion_note = (
        "the 50-per-method queue is complete."
        if queue_status == "complete"
        else "empty labels in the expanded 50-per-method queue are not imputed."
    )
    method_labels = {
        "CVSS + EPSS + KEV priority only": "CVSS/EPSS/KEV only",
    }
    order = [
        "CPE-only",
        "CVSS + EPSS + KEV priority only",
        "LLM-only rerank",
        "RAG-only",
        "RAG + KG",
        "Ours",
        "Ours-strict",
    ]
    by_method = {row["method"]: row for row in summary}
    manual_methods = manual.get("methods", {})
    lines = [
        "% Auto-generated by experiments/generate_statistical_reporting_tables.py",
        "\\begin{table*}[t]",
        "  \\centering",
        "  \\caption{Exp 5: asset-level CVE attribution auditability. Recall, nDCG, and MRR use the weak CVE oracle only for candidate ranking. Audit pass counts strong+reasonable completed labels only; the manual audit sample contains 350 completed pairs with 50 per method.}",
        "  \\label{tab:exp05_main}",
        "  \\small",
        "  \\setlength{\\tabcolsep}{3.5pt}",
        "  \\begin{tabular}{lrrrrrrrlrr}",
        "    \\toprule",
        "    Method & R@5 & R@10 & nDCG@10 & MRR & Support & S/R Path & Audit Pass & 95\\% CI & Audit Unsup. & Audit Wrong \\\\",
        "    \\midrule",
    ]
    for method in order:
        row = by_method[method]
        stats = manual_methods.get(method, {})
        lines.append(
            "    "
            + " & ".join([
                _escape(method_labels.get(method, method)),
                _fmt(row.get("cve_recall@5")),
                _fmt(row.get("cve_recall@10")),
                _fmt(row.get("cve_ndcg@10")),
                _fmt(row.get("cve_mrr")),
                _fmt(row.get("explanation_support_rate")),
                _fmt(row.get("strong_or_reasonable_path_rate")),
                _fmt(stats.get("pass_rate", row.get("manual_audit_pass_rate"))),
                _fmt_ci(stats.get("bootstrap_ci95")),
                _fmt(_manual_label_rate(stats, "unsupported", row.get("manual_label_unsupported_rate"))),
                _fmt(_manual_label_rate(stats, "wrong", row.get("manual_label_wrong_rate"))),
            ])
            + " \\\\"
        )
    lines.extend([
        "    \\bottomrule",
        "  \\end{tabular}",
        "  \\vspace{0.35em}",
        "  \\begin{minipage}{0.98\\linewidth}",
        "    \\footnotesize",
        "    \\textit{Notes.} Support is the explanation support rate. S/R Path is the automatic strong-or-reasonable evidence-path rate. Completed audit labels currently cover "
        + str(queue.get("completed_labels", "NA"))
        + " asset--CVE pairs; "
        + queue_completion_note
        + _exp5_label_source_note()
        + " Ours-strict filters weak or unsupported evidence paths; this supports an auditability-improvement claim rather than a broad ranking-superiority claim.",
        "  \\end{minipage}",
        "\\end{table*}",
    ])
    _write(TABLE_DIR / "exp05_main.tex", lines)


