"""experiments/exp_arcs/dag — the attributed evidence DAG (Step 1.2).

Builds, from one recorded infra_v1 bundle, the per-run evidence DAG that is
ARCS's input: nodes are the typed records (source_artifact / evidence_event /
claim / decision / report_item), edges are the data-flow dependencies, and every
node carries ``v = (source_family, r(v), c(v), h(v))`` from the frozen cost/harm
spec (Step 1.3).

Data-flow edges (parent → child = "parent contaminates child"):

    source_artifact → evidence_event      (evidence.raw_ref = artifact:<id>)
    evidence_event  → claim               (claim's decision.supporting_evidence)
    claim           → decision            (decision.claim_id)
    evidence_event  → decision            (decision.supporting/contradicting)
    claim           → report_item         (report.claim_id)
    decision        → report_item         (report.decision_id)
    evidence_event  → report_item         (report.evidence_event_ids)

Repairability: only source_artifact / evidence_event nodes are directly
re-runnable (a repair action re-collects them). claim / decision / report_item
are consequences — their v aggregates their supporting evidence (cost=Σ,
harm=Σ, reversibility=max rank) and ``repairable=False``.
"""
from __future__ import annotations

import json
from collections import deque
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from experiments.exp_arcs.cost_harm import cost_harm_reversibility, spec_version_hash


@dataclass
class Dag:
    nodes: dict[str, dict[str, Any]] = field(default_factory=dict)
    edges: list[tuple[str, str]] = field(default_factory=list)
    cost_harm_spec_hash: str = ""

    def children(self, node_id: str) -> list[str]:
        return [d for s, d in self.edges if s == node_id]

    def descendants(self, node_id: str) -> set[str]:
        """All nodes reachable downstream from ``node_id`` (excluding itself)."""
        adj: dict[str, list[str]] = {}
        for s, d in self.edges:
            adj.setdefault(s, []).append(d)
        seen: set[str] = set()
        queue = deque(adj.get(node_id, []))
        while queue:
            n = queue.popleft()
            if n in seen:
                continue
            seen.add(n)
            queue.extend(adj.get(n, []))
        return seen


def scope_cost(dag: "Dag", scope: Any) -> dict[str, Any]:
    """Cost/harm of a repair scope at (target, source_family) INVOCATION grain.

    One tool run re-collects all of a host's evidence for a family, so a scope is
    charged per distinct (target, family) invocation, not per record. Non-repairable
    (full_replay/derived) and unknown nodes are skipped. This is the C(S)/H(S) the
    plan's anchors (dns=1 … http=3) are stated in, and the unit for ρC and B₀.
    """
    seen: set[tuple[Any, str]] = set()
    cost = harm = 0
    n_irreversible = 0
    for nid in scope:
        node = dag.nodes.get(nid)
        if not node or not node.get("repairable"):
            continue
        key = (node.get("target"), node["source_family"])
        if key in seen:
            continue
        seen.add(key)
        cost += node["cost"]
        harm += node["harm"]
        if node["reversibility_rank"] == 3:
            n_irreversible += 1
    return {"cost": cost, "harm": harm, "n_invocations": len(seen),
            "n_irreversible": n_irreversible}


def _rows(run_dir: Path, name: str) -> list[dict[str, Any]]:
    path = run_dir / name
    if not path.exists():
        return []
    return [json.loads(ln) for ln in path.read_text().splitlines() if ln.strip()]


def _leaf_v(source_family: str, target: str | None) -> dict[str, Any]:
    ch = cost_harm_reversibility(source_family)
    # A leaf is a *selectively re-collectable* observation. Families that map to
    # full_replay (llm_inference / system_diagnostic / other) are derived — they
    # cannot be re-collected by a targeted tool run, only regenerated by a full
    # replay — so they are NOT repairable leaves; outputs depending only on them
    # are unrepairable-by-leaf. cost/harm are per ONE (target, family) tool
    # invocation; scope_cost() dedupes a scope to invocations (not records).
    return {"source_family": source_family, "target": target, "action": ch["action"],
            "cost": ch["cost"], "harm": ch["harm"],
            "reversibility": ch["reversibility"],
            "reversibility_rank": ch["reversibility_rank"],
            "repairable": ch["action"] != "full_replay"}


def build_dag(run_dir: str | Path) -> Dag:
    run_dir = Path(run_dir)
    dag = Dag(cost_harm_spec_hash=spec_version_hash())

    evidence = _rows(run_dir, "evidence_event.jsonl")
    artifacts = _rows(run_dir, "source_artifact.jsonl")
    claims = _rows(run_dir, "claim.jsonl")
    decisions = _rows(run_dir, "decision.jsonl")
    reports = _rows(run_dir, "report_item.jsonl")

    # artifact_id referenced by each evidence event (raw_ref = "artifact:<id>");
    # a source_artifact inherits the family/target of the evidence that cites it.
    ev_family = {e["evidence_event_id"]: e.get("source_family", "other") for e in evidence}
    ev_target = {e["evidence_event_id"]: e.get("target") for e in evidence}
    art_family: dict[str, str] = {}
    art_target: dict[str, str | None] = {}
    for e in evidence:
        ref = str(e.get("raw_ref", ""))
        if ref.startswith("artifact:"):
            aid = ref.split(":", 1)[1]
            art_family.setdefault(aid, e.get("source_family", "other"))
            art_target.setdefault(aid, e.get("target"))

    # ── leaf nodes (selectively re-collectable observations) ──
    for a in artifacts:
        aid = a["artifact_id"]
        dag.nodes[aid] = {"type": "source_artifact",
                          **_leaf_v(art_family.get(aid, "other"), art_target.get(aid))}
    for e in evidence:
        eid = e["evidence_event_id"]
        dag.nodes[eid] = {"type": "evidence_event",
                          **_leaf_v(ev_family[eid], ev_target[eid])}
        ref = str(e.get("raw_ref", ""))
        if ref.startswith("artifact:") and ref.split(":", 1)[1] in dag.nodes:
            dag.edges.append((ref.split(":", 1)[1], eid))  # artifact → evidence

    # ── derived nodes: v aggregates supporting evidence ──
    def _derived(support_ids: list[str], node_type: str) -> dict[str, Any]:
        vs = [dag.nodes[s] for s in support_ids if s in dag.nodes]
        return {
            "type": node_type,
            "source_family": sorted({v["source_family"] for v in vs}),
            "action": "derived",
            "cost": sum(v["cost"] for v in vs),
            "harm": sum(v["harm"] for v in vs),
            "reversibility_rank": max((v["reversibility_rank"] for v in vs), default=0),
            "repairable": False,
        }

    # claim → supporting evidence, recovered from the decision ledger: claim
    # records carry no evidence linkage, but the decision that evaluates a claim
    # lists the evidence supporting it (decision.claim_id + supporting ids).
    claim_support: dict[str, set[str]] = {}
    for d in decisions:
        cid = d.get("claim_id")
        if cid is not None:
            claim_support.setdefault(cid, set()).update(
                d.get("supporting_evidence_event_ids", []))

    for c in claims:
        cid = c["claim_id"]
        sup = sorted(claim_support.get(cid, set()))
        dag.nodes[cid] = _derived(sup, "claim")   # v aggregates supporting evidence
        for e in sup:
            if e in dag.nodes:
                dag.edges.append((e, cid))                             # evidence → claim
    for d in decisions:
        sup = d.get("supporting_evidence_event_ids", []) + d.get("contradicting_evidence_event_ids", [])
        dag.nodes[d["decision_id"]] = _derived(sup, "decision")
        if d.get("claim_id") in dag.nodes:
            dag.edges.append((d["claim_id"], d["decision_id"]))       # claim → decision
        for e in sup:
            if e in dag.nodes:
                dag.edges.append((e, d["decision_id"]))                # evidence → decision
    for r in reports:
        ev_ids = r.get("evidence_event_ids", [])
        dag.nodes[r["report_item_id"]] = _derived(ev_ids, "report_item")
        for parent in (r.get("claim_id"), r.get("decision_id")):
            if parent in dag.nodes:
                dag.edges.append((parent, r["report_item_id"]))        # claim/decision → report
        for e in ev_ids:
            if e in dag.nodes:
                dag.edges.append((e, r["report_item_id"]))             # evidence → report

    return dag
