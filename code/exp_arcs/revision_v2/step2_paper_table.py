"""Paper table for Step 2 (statistical baselines), rendered from the committed
step2_baselines_v1.json — no recomputation. Adds realized clean-run alert rates (4 dp, so
0.1055 is not shown as 0.105) and mean cost/C*, which step2_baselines_table.tex omits.

    .venv/bin/python experiments/exp_arcs/revision_v2/step2_paper_table.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "step2_baselines_paper_table.tex"
NAMES = {"robust_z": "robust-$z$", "iforest": "Isolation Forest", "lof": "LOF ($k{=}20$)"}


def main() -> int:
    r = json.loads((HERE / "step2_baselines_v1.json").read_text())

    def row(name, auc_roc, auc_pr, s, clean):
        su = s["success"]
        return (f"{name} & {auc_roc:.3f} & {auc_pr:.3f} & {s['detect1']['org_mean']:.3f} & "
                f"{s['detect3']['org_mean']:.3f} & {clean['macro_rate']:.4f} & "
                f"{su['org_mean']:.3f} [{su['ci95'][0]:.3f}, {su['ci95'][1]:.3f}] & "
                f"{s['cost_over_Cstar_all']['org_mean']:.2f} \\\\")

    c = r["combined"]["primary"]
    lines = [
        r"\begin{table}[t]\centering\footnotesize\setlength{\tabcolsep}{4pt}",
        r"\caption{Combined detector (validator flag $\cup$ peer-anomaly at $t=0.5$ $\cup$ discovery manifest) vs.\ generic unsupervised detectors (comparison protocol frozen after the main-grid results were known and before this detector comparison). "
        r"Baselines are fit within each run on $20$ deployment-visible per-host features; their alert "
        r"threshold is calibrated by leave-one-organization-out on the other organizations' clean runs at the "
        r"combined detector's macro clean-run alert rate ($\alpha=0.106$). \emph{Clean alert}: realized macro "
        r"clean-run alert rate on the held-out clean runs. Detect@$k$ is tie-aware; Success is offline counterfactual "
        r"recovery with the same clean-DAG host-grain action mapper (brackets: organization-level bootstrap $95\%$ CI); "
        r"cost is the mean specification-cost ratio $c/C^\ast$ over all $180$ cells, not execution cost.}",
        r"\label{tab:stat-baselines}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{l rr rr r r r}\toprule",
        r"detector & AUC-ROC & AUC-PR & Detect@1 & Detect@3 & clean alert & Success & cost/$C^\ast$ \\\midrule",
        row(r"combined ($t=0.5$)", c["auc"]["auc_roc_raw"], c["auc"]["auc_pr_raw"],
            c["summary"], c["clean_run_alerts"]),
    ]
    for ma, label in (("manifest_aware", "manifest-aware candidates"), ("manifest_free", "manifest-free candidates")):
        lines.append(r"\midrule\multicolumn{8}{l}{\emph{" + label + r"}} \\")
        for d in ("robust_z", "iforest", "lof"):
            b = r["baselines"][f"{d}|{ma}"]
            op = b["by_alpha"]["primary"]
            lines.append(row(NAMES[d], b["threshold_free"]["auc_roc"], b["threshold_free"]["auc_pr"],
                             {**op["summary"], "detect1": b["threshold_free"]["detect1"],
                              "detect3": b["threshold_free"]["detect3"]}, op["clean_run_alerts"]))
    lines += [r"\bottomrule\end{tabular}}", r"\end{table}"]
    OUT.write_text("% generated by experiments/exp_arcs/revision_v2/step2_paper_table.py from step2_baselines_v1.json — do not edit\n"
                   + "\n".join(lines) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
